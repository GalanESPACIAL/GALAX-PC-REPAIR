-- ---------------------------------------------------------------------
-- 5. MAPEO auth.uid() -> usuarios.id (para RLS de propiedad)
--    SECURITY DEFINER evita recursión con las políticas de `usuarios`.
-- ---------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.current_local_user_id()
RETURNS integer
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
    SELECT u.id
      FROM public.usuarios u
     WHERE u.supabase_uid = auth.uid()
     LIMIT 1
$$;

REVOKE ALL ON FUNCTION public.current_local_user_id() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.current_local_user_id() TO anon, authenticated, service_role;

