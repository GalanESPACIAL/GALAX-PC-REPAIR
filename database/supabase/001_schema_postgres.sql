CREATE OR REPLACE FUNCTION public.gx_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_ARGV[0] = 'updated_at' THEN
        NEW.updated_at := now();
    ELSIF TG_ARGV[0] = 'actualizado_en' THEN
        NEW.actualizado_en := now();
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_roles_updated_at ON public.roles;
CREATE TRIGGER trg_roles_updated_at BEFORE UPDATE ON public.roles
    FOR EACH ROW EXECUTE FUNCTION public.gx_set_updated_at('updated_at');
